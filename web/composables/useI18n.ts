// Resolve locale: cookie > localStorage > browser > 'id' (default)
function resolveLocale(): string {
  try {
    const cookie = document.cookie.split(';').find(c => c.trim().startsWith('jkr_lang='))
    if (cookie) {
      const v = cookie.split('=')[1].trim()
      if (v in dictionaries) return v
    }
  } catch {}
  try {
    const stored = localStorage.getItem('jkr_lang')
    if (stored && stored in dictionaries) return stored
  } catch {}
  const nav = typeof navigator !== 'undefined' ? navigator.language?.slice(0, 2) : null
  return (nav && nav in dictionaries) ? nav : 'en'
}

const currentLocale = ref<string>(resolveLocale())

export function t(key: string, params?: Record<string, string | number>): string {
  const dict = dictionaries[currentLocale.value] || dictionaries.id
  let text = dict[key] || dictionaries.en[key] || key
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      text = text.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v))
    }
  }
  return text
}

export function setLocale(locale: string) {
  if (!(locale in dictionaries)) return
  currentLocale.value = locale
  try {
    document.cookie = `jkr_lang=${locale};max-age=31536000;path=/`
    localStorage.setItem('jkr_lang', locale)
  } catch {}
}

export function useI18n() {
  return { t, setLocale, locale: computed(() => currentLocale.value) }
}
